# [1차]: 생성 결과물 검증 및 교정 모듈의 역할을 설명하는 다중 라인 모듈 독스트링의 시작입니다.
# [2차]: "이 파일은 AI가 써온 글을 맞춤법 검사기처럼 꼼꼼하게 검사하고, 부족한 부분을 자동으로 채워주는 교정·교열 편집국입니다"라는 현판입니다.
"""
# [1차]: 생성된 커밋 메시지 및 PR 초안의 형식을 검증하고 실무 규칙에 맞게 자동 보정(후처리)하는 모듈임을 명시합니다.
# [2차]: AI가 가끔 엉뚱하게 마크다운 따옴표를 붙이거나 헤더를 빼먹었을 때, 사람이 일일이 고치지 않아도 프로그램이 알아서 고쳐주는 든든한 AS 센터입니다.
생성된 커밋 메시지 및 PR 초안의 형식을 검증하고 실무 규칙에 맞게 자동 보정(후처리)하는 모듈
# [1차]: 모듈 독스트링을 닫는 삼중 따옴표입니다.
# [2차]: 현판 닫기.
"""

# [1차]: 제목 마크다운 기호 제거 및 PR 헤더 패턴 매칭을 위해 re 모듈을 임포트합니다.
# [2차]: 특정 글자 모양(#, Why, What 등)을 귀신같이 찾아내는 정밀 스캐너를 가져옵니다.
import re
# [1차]: 함수 인자 및 반환값의 정적 타입 힌트를 위해 typing 모듈에서 List, Optional, Tuple을 임포트합니다.
# [2차]: 파이썬 함수들에게 "이 주머니엔 무슨 자료가 들어오는지" 알려주기 위한 라벨표입니다.
from typing import List, Optional, Tuple


# [1차]: 텍스트 앞뒤의 마크다운 코드 블록(```)을 제거하는 strip_markdown_fences 함수의 선언부입니다.
# [2차]: AI가 가끔 텍스트를 택배 박스(```)로 감싸서 보내는데, 내용물만 쏙 꺼내기 위해 택배 상자 포장지를 뜯어내는 함수입니다.
def strip_markdown_fences(text: str) -> str:
    # [1차]: 함수의 역할을 설명하는 한 줄 독스트링입니다.
    # [2차]: 함수 설명서입니다.
    """텍스트 앞뒤를 감싸고 있는 마크다운 코드 블록(```)을 제거합니다."""
    # [1차]: 텍스트의 앞뒤 공백 및 줄바꿈 문자를 1차로 제거합니다.
    # [2차]: 포장지 뜯기 전에 겉에 묻은 먼지를 탈탈 텁니다.
    text = text.strip()
    # [1차]: 텍스트가 마크다운 코드 블록 기호("```")로 시작하는지 검사합니다.
    # [2차]: "택배 박스로 포장되어 있나?" 하고 확인합니다.
    if text.startswith("```"):
        # [1차]: 텍스트를 줄 단위로 분할하여 리스트로 만듭니다.
        # [2차]: 여러 줄의 편지를 한 줄씩 분리합니다.
        lines = text.splitlines()
        # [1차]: 텍스트가 2줄 이상 존재하는지 확인합니다.
        # [2차]: 뚜껑 말고 알맹이 내용이 진짜 들어있는지 봅니다.
        if len(lines) >= 2:
            # [1차]: 첫 번째 라인(``` 또는 ```markdown)을 슬라이싱으로 제거합니다.
            # [2차]: 택배 박스의 윗면 뚜껑("```")을 가위로 잘라 버립니다.
            lines = lines[1:]
        # [1차]: 마지막 라인이 백틱("```") 기호인지 검사합니다.
        # [2차]: 택배 박스의 맨 밑바닥 받침대("```")도 붙어있는지 확인합니다.
        if lines and lines[-1].strip() == "```":
            # [1차]: 마지막 라인을 슬라이싱으로 잘라냅니다.
            # [2차]: 박스 밑바닥도 가위로 잘라 버립니다.
            lines = lines[:-1]
        # [1차]: 포장 라인이 제거된 줄들을 다시 줄바꿈 문자로 합치고 여백을 정돈합니다.
        # [2차]: 포장지를 싹 벗겨낸 순수한 편지 알맹이만 남겨서 돌려줍니다.
        text = "\n".join(lines).strip()
    # [1차]: 마크다운 블록이 벗겨진 순수 텍스트를 반환합니다.
    # [2차]: 깨끗해진 알맹이 글을 반환합니다.
    return text


# [1차]: 제목 문자열에서 불필요한 기호를 제거하고 최대 길이를 제한하는 clean_title 함수 선언부입니다.
# [2차]: 신문 1면 헤드라인에 '#' 같은 낙서가 있으면 지우고, 제목이 너무 길면 뒷부분을 "..."으로 줄여주는 제목 미용사입니다.
def clean_title(title: str, max_length: int) -> str:
    # [1차]: 함수의 목적을 명시한 독스트링입니다.
    # [2차]: 설명서입니다.
    """제목에서 불필요한 마크다운 기호를 제거하고 최대 길이를 초과할 경우 안전하게 자릅니다."""
    # [1차]: 제목 문자열 양쪽의 공백을 제거합니다.
    # [2차]: 제목 양옆 여백을 텁니다.
    title = title.strip()
    # [1차]: 정규표현식을 통해 제목 앞단의 마크다운 헤더 기호(^#+\s*)를 제거합니다.
    # [2차]: AI가 가끔 습관처럼 붙이는 "# feat: 회원가입"에서 앞의 "# " 기호를 지우개로 싹 지웁니다.
    title = re.sub(r"^#+\s*", "", title)

    # [1차]: 제목 글자 수가 최대 허용 길이(max_length)를 초과하는지 검사합니다.
    # [2차]: "제목이 72자나 80자를 넘어서 너무 긴가?" 하고 자로 재봅니다.
    if len(title) > max_length:
        # [1차]: 최대 길이에서 3글자를 뺀 위치까지 자르고 말줄임표("...")를 붙여 길이를 맞춥니다.
        # [2차]: 넘치는 글자를 자르고 끝에 센스 있게 "..."을 달아주어 딱 규격 길이에 맞춥니다.
        title = title[: max_length - 3] + "..."
    # [1차]: 정제된 제목 문자열을 반환합니다.
    # [2차]: 완벽하게 다듬어진 헤드라인 제목을 건넵니다.
    return title


# [1차]: 커밋 메시지 형식을 검증하고 실무 규칙에 맞게 자동 보정하는 validate_and_fix_commit 함수 선언부입니다.
# [2차]: "커밋 메시지 검사관 나와라!" 하고 부르는 커밋 품질 보증 총괄 함수입니다.
def validate_and_fix_commit(
    raw_text: str,
    changed_files: Optional[List[str]] = None
) -> str:
    # [1차]: 함수의 검증 규칙과 보정 기준을 기술하는 Docstring의 시작입니다.
    # [2차]: 설명서 시작.
    """
    # [1차]: 커밋 메시지 검증 요건(72자 이내 제목, 빈 줄, 불릿/파일 언급 1개 이상 보장)을 명시합니다.
    # [2차]: 실무에서 시니어에게 혼나지 않는 커밋 메시지 3대 규칙 안내입니다.
    커밋 메시지 형식 검증 및 후처리:
    - 1줄 제목: 최대 72자 이내로 보정 (50자 권장)
    - 제목과 본문 사이 1줄 공백 보장
    - 본문 요약: 파일 언급 또는 불릿('- ') 1개 이상 포함 보장
    # [1차]: Docstring을 닫습니다.
    # [2차]: 설명서 끝.
    """
    # [1차]: 응답 텍스트에서 마크다운 코드 블록 기호를 제거합니다.
    # [2차]: 택배 상자 포장지가 씌워져 있다면 먼저 시원하게 벗깁니다.
    text = strip_markdown_fences(raw_text)
    # [1차]: 줄 단위로 텍스트를 나눕니다.
    # [2차]: 커밋 메시지를 줄별로 분리합니다.
    lines = text.splitlines()

    # [1차]: AI 응답 텍스트가 완전히 비어있는지 검사합니다.
    # [2차]: AI가 아무 대답도 못 하고 백지를 냈는지 확인합니다.
    if not lines:
        # [1차]: 비어있는 경우 기본 커밋 제목을 지정합니다.
        # [2차]: 백지를 냈더라도 시스템이 멈추지 않게 "chore: 변경 사항 적용"이라는 모범 답안 제목을 대신 달아줍니다.
        title = "chore: 변경 사항 적용"
        # [1차]: 본문 줄 목록을 빈 리스트로 초기화합니다.
        # [2차]: 본문 바구니를 비워둡니다.
        body_lines = []
    # [1차]: 응답 라인이 존재하는 정상 분기입니다.
    # [2차]: 정상적으로 글을 써왔을 때입니다.
    else:
        # [1차]: 첫 번째 라인을 clean_title로 72자 이내로 정제하여 제목으로 삼습니다.
        # [2차]: 첫 줄을 가져와서 마크다운 샵(#)을 떼고 72자 이내로 예쁘게 제목을 다듬습니다.
        title = clean_title(lines[0], max_length=72)
        # [1차]: 두 번째 라인부터 끝까지를 본문 줄들로 분리합니다.
        # [2차]: 첫 줄(제목)을 뺀 나머지 아래 줄들을 본문 바구니에 담습니다.
        body_lines = lines[1:]

    # [1차]: 제목 바로 다음의 불필요한 연속 빈 줄들을 pop(0)으로 제거합니다.
    # [2차]: 제목 바로 아래에 띄어쓰기가 서너 칸씩 들어가 있으면 한 줄만 남길 수 있게 싹 지워버립니다.
    while body_lines and not body_lines[0].strip():
        body_lines.pop(0)

    # [1차]: 본문 라인들을 다시 결합하고 양쪽 공백을 제거하여 본문 문자열을 만듭니다.
    # [2차]: 본문 글자들을 보기 좋게 하나의 문단으로 엮습니다.
    body_text = "\n".join(body_lines).strip()

    # [1차]: 본문 중 한 줄이라도 글머리 기호("- " 또는 "* ")로 시작하는지 검사합니다.
    # [2차]: 본문 중에 글머리 기호(동그라미나 하이픈)로 요약된 줄이 최소 1개라도 있는지 찾습니다.
    # 마이: 
    # any: 해당되는게 한줄이라도 있으면 트루로 반환
    # 바디 라인에서 라인을 뽑아와서 스트라이프로 앞뒤 공백을 제거하고, 
    # .startswith: "이 글자로 시작하니?" 하고 문장의 맨 첫머리를 검사하여 그러하면 트루를 내보냄
    # 모양이 이쁘게 쓰였는지 확인하는 코드
    has_bullet = any(line.strip().startswith(("- ", "* ")) for line in body_lines)
    # [1차]: changed_files가 None일 경우 빈 리스트를 기본값으로 지정합니다.
    # [2차]: 파일 목록이 없으면 빈 목록으로 세팅합니다.
    files = changed_files or []
    # [1차]: 변경 파일명 중 하나라도 본문에 포함되어 있는지 검사합니다.
    # [2차]: 본문 글 중에 "src/cli.py" 같은 파일 이름이 실제로 적혀 있는지 확인합니다.
    # 마이: 적혀졌는지 찾아야할 파일이 있는지 1차 검사, 2차로 본문에 파일이 적혀있는지 확인, 하나라도 적히면 트루인셈
    mentions_file = any(f in body_text for f in files) if files else False

    # [1차]: 불릿도 없고 파일 언급도 없는 등 본문 품질 기준에 미달하는지 검사합니다.
    # [2차]: "AI가 본문을 대충 한 줄로 뭉개거나 날림으로 썼는가?"를 감시합니다.
    if not has_bullet and not mentions_file:
        # [1차]: 보충 문장들을 담을 리스트를 초기화합니다.
        # [2차]: 부족한 점수를 채워줄 추가 보충제 바구니입니다.
        supplementary = []
        # [1차]: 변경 파일 목록이 있는 경우 상위 3개 파일을 언급하는 불릿을 작성합니다.
        # [2차]: 실제로 고친 파일 이름 3개를 골라서 "- 변경된 파일: fileA, fileB" 항목을 자동으로 써줍니다.
        if files:
            # [1차]: 최대 3개 파일 경로를 쉼표로 연결합니다.
            # [2차]: 3개 파일 이름을 쉼표로 잇습니다.
            target_files = ", ".join(files[:3])
            # [1차]: 변경 파일 안내 불릿 라인을 추가합니다.
            # [2차]: 파일 목록 불릿을 바구니에 담습니다.
            supplementary.append(f"- 변경된 파일: {target_files}")
        # [1차]: 핵심 변경 사항 기본 불릿 라인을 추가합니다.
        # [2차]: "- 핵심 변경 사항 구현 및 반영" 불릿을 자동으로 달아줍니다.
        supplementary.append("- 핵심 변경 사항 구현 및 반영")

        # [1차]: 기존 본문이 존재하는 경우 그 뒤에 개행 후 보충 항목을 추가합니다.
        # [2차]: AI가 쓴 글 아래에 보충 내용을 자연스럽게 이어 붙입니다.
        if body_text:
            body_text = body_text + "\n" + "\n".join(supplementary)
        # [1차]: 본문이 비어있었던 경우 보충 항목 자체를 본문으로 설정합니다.
        # [2차]: 본문이 비어있었으면 보충 항목을 본문 전체로 채워 넣습니다.
        else:
            body_text = "\n".join(supplementary)

    # [1차]: 제목, 빈 줄 1개("\n\n"), 보정된 본문을 결합한 최종 커밋 메시지를 반환합니다.
    # [2차]: [제목] + [빈 줄 1개] + [불릿이 완비된 고품질 본문]을 조립하여 완성된 커밋 메시지를 출하합니다.
    return f"{title}\n\n{body_text}"


# [1차]: PR 초안 형식을 검증하고 3대 필수 섹션을 자동 보정하는 validate_and_fix_pr 함수 선언부입니다.
# [2차]: "PR 초안 검사관 나와라!" 하고 부르는 PR 문서 품질 보증 총괄 함수입니다.
def validate_and_fix_pr(
    raw_text: str,
    changed_files: Optional[List[str]] = None
) -> str:
    # [1차]: PR 검증 요건을 설명하는 Docstring의 시작입니다.
    # [2차]: 설명서 시작.
    """
    # [1차]: PR 제목(80자) 및 Why, What, How to Test 헤더 검증 규칙을 기술합니다.
    # [2차]: 깃허브에서 동료들이 좋아하는 완벽한 PR 양식 가이드입니다.
    PR 제목 및 본문 템플릿 검증 및 후처리:
    - 1줄 제목: 최대 80자 이내 보정
    - 제목과 본문 사이 공백 보장
    - 필수 3대 섹션 헤더(Why, What, How to Test) 존재 검증 및 자동 보충
    - 각 섹션별 최소 1개 이상의 불릿('- ') 보장
    # [1차]: Docstring을 닫습니다.
    # [2차]: 설명서 끝.
    """
    # [1차]: 마크다운 코드 블록 백틱 기호를 제거합니다.
    # [2차]: 겉포장 상자를 벗깁니다.
    text = strip_markdown_fences(raw_text)
    # [1차]: 줄 단위로 분할합니다.
    # [2차]: 줄별로 분리합니다.
    lines = text.splitlines()

    # [1차]: 응답 내용이 완전히 비어있는지 검사합니다.
    # [2차]: AI가 빈 종이를 냈는지 봅니다.
    if not lines:
        # [1차]: 비어있는 경우 기본 PR 제목을 지정합니다.
        # [2차]: "PR: 코드 변경 사항 반영"이라는 기본 제목을 달아줍니다.
        title = "PR: 코드 변경 사항 반영"
        # [1차]: 본문 줄 목록을 빈 리스트로 둡니다.
        # [2차]: 본문 바구니를 비워둡니다.
        body_lines = []
    # [1차]: 내용이 존재하는 경우입니다.
    # [2차]: 정상적으로 글을 써왔을 때입니다.
    else:
        # [1차]: 첫 번째 줄을 80자 이내로 정제하여 PR 제목으로 지정합니다.
        # [2차]: 첫 줄을 가져와 80자 이내의 깔끔한 PR 제목으로 다듬습니다.
        title = clean_title(lines[0], max_length=80)
        # [1차]: 두 번째 줄부터를 본문 줄로 잡습니다.
        # [2차]: 아래 줄들을 본문 줄들로 분리합니다.
        body_lines = lines[1:]
        # [1차]: 제목 바로 다음의 연속 빈 줄들을 제거합니다.
        # [2차]: 제목 바로 아래 쓸데없는 공백 줄들을 지웁니다.
        while body_lines and not body_lines[0].strip():
            body_lines.pop(0)

    # [1차]: Why, What, How to Test 섹션 헤더를 대소문자 구분 없이 감지하는 정규표현식 딕셔너리입니다.
    # [2차]: "### Why", "## What", "# How to Test" 등 대소문자나 샵 개수에 상관없이 3대 헤더를 찾아내는 정밀 레이더입니다.
    section_patterns = {
        "Why": re.compile(r"(?i)^#*\s*Why\b"),
        "What": re.compile(r"(?i)^#*\s*What\b"),
        "How to Test": re.compile(r"(?i)^#*\s*How to Test\b"),
    }

    # [1차]: 3대 섹션별 본문 줄들을 담아둘 딕셔너리를 빈 리스트로 초기화합니다.
    # [2차]: 'Why 방', 'What 방', 'How to Test 방' 등 3개의 빈 서랍을 만듭니다.
    sections_content = {sec: [] for sec in section_patterns}
    # [1차]: 첫 섹션 등장 이전의 서론 줄들을 모을 리스트입니다.
    # [2차]: 3대 서랍에 들어가기 전, 앞머리에 적힌 소개글을 담을 바구니입니다.
    intro_lines: List[str] = []
    # [1차]: 현재 탐색 중인 활성 섹션 이름을 기억할 변수입니다.
    # [2차]: "지금 내가 어느 서랍에 편지를 집어넣고 있는 중인가?"를 기억하는 손가락 표시입니다.
    current_sec = None

    # [1차]: 본문 줄들을 순서대로 순회합니다.
    # [2차]: AI가 써온 본문 글을 위에서부터 한 줄씩 분류 작업합니다.
    for line in body_lines:
        # [1차]: 헤더 일치 여부 임시 변수를 None으로 둡니다.
        # [2차]: 이번 줄이 방 이름표인지 확인할 변수입니다.
        matched_sec = None
        # [1차]: 3개 패턴과 대조하여 헤더 일치 여부를 검사합니다.
        # [2차]: 3개의 이름표(Why, What, How to Test) 중 하나와 맞는지 레이더를 돌립니다.
        for sec_name, pattern in section_patterns.items():
            if pattern.match(line.strip()):
                matched_sec = sec_name
                break

        # [1차]: 새로운 헤더 줄을 만나면 현재 활성 섹션을 변경합니다.
        # [2차]: "아! 여기서부터는 What 방이구나!" 하고 현재 작업 서랍을 바꿉니다.
        if matched_sec:
            current_sec = matched_sec
        # [1차]: 헤더가 아니고 활성 섹션이 존재하면 해당 섹션 리스트에 라인을 추가합니다.
        # [2차]: 방 안에 들어갈 내용물 문장을 해당 서랍에 쏙 집어넣습니다.
        elif current_sec:
            sections_content[current_sec].append(line)
        # [1차]: 아직 섹션 헤더를 만나기 전의 줄이면 서론 리스트에 보관합니다.
        # [2차]: 방이 시작되기 전 복도에 놓인 문장이면 소개글 바구니에 담습니다.
        else:
            intro_lines.append(line)

    # [1차]: 변경 파일 목록을 가져옵니다.
    # [2차]: 고친 파일 목록을 확인합니다.
    files = changed_files or []
    # [1차]: 섹션이 누락되었을 때 자동 삽입할 기본 모범 불릿 딕셔너리를 정의합니다.
    # [2차]: AI가 혹시라도 까먹고 방을 비워뒀을 때 대신 꽂아줄 "비상용 표준 문장 세트"입니다.
    default_bullets = {
        "Why": "- 기능 개선 및 요구사항 충족을 위한 코드 변경",
        "What": f"- 주요 파일 변경: {', '.join(files[:3])}" if files else "- 주요 코드 로직 구현 및 리팩토링",
        "How to Test": "- 관련 단위 테스트 실행 및 변경 기능 동작 검증"
    }

    # [1차]: 재구성된 완제품 PR 본문 라인들을 담을 리스트입니다.
    # [2차]: 서랍에서 정리된 문장들을 꺼내서 완성된 PR 문서를 붙일 깨끗한 새 도화지입니다.
    reconstructed: List[str] = []
    # [1차]: 서론 문장이 유효하게 존재하면 맨 앞에 배치하고 빈 줄을 둡니다.
    # [2차]: 머리말 소개글이 있었으면 맨 위에 적고 한 칸 띄웁니다.
    if intro_lines and any(l.strip() for l in intro_lines):
        reconstructed.extend([l for l in intro_lines if l.strip()])
        reconstructed.append("")

    # [1차]: Why, What, How to Test 순서로 루프를 돌며 본문을 재조립합니다.
    # [2차]: 사내 규정 순서인 [Why] ➡️ [What] ➡️ [How to Test] 순서대로 도화지에 인쇄합니다.
    for sec in ["Why", "What", "How to Test"]:
        # [1차]: 마크다운 H3 헤더("### Why")를 추가합니다.
        # [2차]: "### Why"라는 굵은 섹션 제목을 찍습니다.
        reconstructed.append(f"### {sec}")
        # [1차]: 해당 섹션에 분류되었던 내용 라인들을 가져옵니다.
        # [2차]: 해당 방에 모아둔 편지 줄들을 꺼내옵니다.
        content = sections_content[sec]
        # [1차]: 공백 라인을 제외한 유효 텍스트 라인만 추출합니다.
        # [2차]: 내용 없는 빈 종이들을 솎아냅니다.
        non_empty = [c.strip() for c in content if c.strip()]

        # [1차]: 불릿 기호로 시작하는 라인들이 있는지 확인합니다.
        # [2차]: 글머리 기호("- ")가 달린 문장이 이미 들어있는지 봅니다.
        bullets = [c for c in non_empty if c.startswith(("- ", "* "))]
        # [1차]: 불릿이 이미 있으면 내용 라인들을 그대로 반영합니다.
        # [2차]: 불릿을 잘 썼으면 AI가 쓴 내용을 칭찬하며 그대로 인쇄합니다.
        if bullets:
            for c in non_empty:
                reconstructed.append(c)
        # [1차]: 내용은 있지만 불릿 기호가 없으면 각 라인에 "- "를 붙여 보정합니다.
        # [2차]: 말은 적었는데 불릿 기호만 까먹고 안 붙였으면 프로그램이 센스 있게 맨 앞에 "- "를 싹 달아줍니다.
        elif non_empty:
            for c in non_empty:
                reconstructed.append(f"- {c}")
        # [1차]: 섹션이 완전히 비어있으면 기본 모범 불릿을 채워 넣습니다.
        # [2차]: 방이 텅 비어있었으면 준비해 둔 비상용 모범 문장을 찰떡같이 꽂아 넣습니다.
        else:
            reconstructed.append(default_bullets[sec])

        # [1차]: 각 섹션 종료 후 빈 줄을 둡니다.
        # [2차]: 섹션 사이 숨고르기 빈 줄입니다.
        reconstructed.append("")

    # [1차]: 완성된 본문 라인들을 줄바꿈 문자로 결합합니다.
    # [2차]: 도화지에 인쇄된 모든 문장들을 하나의 깔끔한 문서로 완성합니다.
    final_body = "\n".join(reconstructed).strip()
    # [1차]: 제목, 빈 줄, 본문을 결합하여 최종 PR 초안 문자열을 반환합니다.
    # [2차]: [PR 제목] + [빈 줄 1개] + [Why/What/How to Test 완비된 본문]의 특급 PR 완성본을 출하합니다.
    return f"{title}\n\n{final_body}"
