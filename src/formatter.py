# [1차]: 터미널 포매터 모듈의 역할을 기술하기 위한 다중 라인 모듈 독스트링의 시작입니다.
# [2차]: "이 파일은 터미널 화면을 예쁘게 인쇄해 주는 전담 디자인실입니다"라는 안내판입니다.
"""
# [1차]: 이 모듈이 콘솔 터미널에 표시될 구분선, 제목 헤더, 실행 메타데이터를 정돈하는 기능을 담당함을 명시합니다.
# [2차]: 투박한 글자 뭉치를 영수증이나 상장처럼 보기 좋게 꾸며주는 템플릿 서식 역할을 한다는 뜻입니다.
터미널 출력용 구분선, 헤더, 메타데이터 포맷팅 모듈
# [1차]: 모듈 독스트링을 닫는 삼중 따옴표입니다.
# [2차]: 모듈 안내판 닫기.
"""

# [1차]: 타입 어노테이션(Type Hinting)을 위해 typing 표준 모듈에서 Any, Dict, Optional을 가져옵니다.
# [2차]: "이 주머니에는 딕셔너리가 들어올 수도 있고, 비어있을 수도(None) 있어"라고 파이썬에게 친절하게 규칙을 적어주는 라벨 스티커 도구들입니다.
from typing import Any, Dict, Optional

# [1차]: 등호(=) 문자를 68번 반복 생성하여 터미널 출력용 굵은 메인 테두리 상수를 선언합니다.
# [2차]: 액자의 가장 바깥쪽 굵은 외곽선(액자 틀)을 만들기 위해 "======..."를 미리 68개 찍어두는 준비 작업입니다.
DIVIDER_DOUBLE = "=" * 68
# [1차]: 하이픈(-) 문자를 68번 반복 생성하여 내부 구획을 나누는 얇은 보조 구분선 상수를 선언합니다.
# [2차]: 영수증의 메뉴와 결제금액 사이에 그어지는 얇은 점선("------...")을 68개 만들어두는 것입니다.
DIVIDER_SINGLE = "-" * 68


# [1차]: 최종 생성 결과 문자열을 조립하여 반환하는 format_output 함수의 정의부입니다.
# [2차]: "예쁜 출력 상자 만들기" 작업을 시작하는 메인 함수입니다.
def format_output(
    # [1차]: 결과물 박스 최상단에 표시할 제목 문자열(예: '커밋 메시지 초안') 매개변수입니다.
    # [2차]: 상자 윗면에 붙일 큰 제목 문패를 건네받습니다.
    title: str,
    # [1차]: AI가 생성한 실제 커밋 메시지 또는 PR 본문 내용 문자열 매개변수입니다.
    # [2차]: 상자 안에 담을 핵심 알맹이(작성된 글 내용)를 건네받습니다.
    content: str,
    # [1차]: 실행 통계(호출수, 소요시간 등)가 담긴 딕셔너리로, 미전달 시 None을 허용합니다.
    # [2차]: 작업 영수증(시간 몇 초 걸렸는지, 모델은 뭘 썼는지) 주머니를 받되, 없어도(None) 괜찮다고 열어둡니다.
    meta: Optional[Dict[str, Any]] = None
# [1차]: format_output 함수의 최종 반환 타입이 완성된 문자열(str)임을 명시합니다.
# [2차]: 모든 재료를 합쳐 하나의 길고 예쁜 텍스트 포스터로 만들어 돌려줍니다.
) -> str:
    # [1차]: 함수의 기능과 목적을 설명하는 함수 레벨 독스트링의 시작입니다.
    # [2차]: 함수 설명서를 엽니다.
    """
    # [1차]: 결과물을 구분선, 헤더, 실행 메타정보와 함께 정돈된 포맷으로 조립함을 설명합니다.
    # [2차]: 선물 포장지처럼 결과물을 예쁘게 패키징한다는 안내문입니다.
    최종 결과물을 구분선, 헤더, 실행 메타정보와 함께 터미널에 정돈된 형태로 출력할 문자열을 생성합니다.
    # [1차]: 독스트링을 닫습니다.
    # [2차]: 설명서 닫기.
    """
    # [1차]: meta 인자가 None일 경우 빈 딕셔너리({})를 기본값으로 할당하여 KeyError나 AttributeError를 방지합니다.
    # [2차]: 손님이 영수증 주머니(meta)를 안 건넸을 때 에러로 뻗지 않도록, 빈 주머니({})를 손에 쥐어주는 안전 운전 코드입니다.
    meta_info = meta or {}
    # [1차]: meta_info에서 "call_count"를 추출하고, 키가 없으면 기본값 1(최소 1회 호출)을 반환합니다.
    # [2차]: "AI한테 몇 번이나 전화 걸어봤어?"를 확인하고, 기록이 없으면 최소 1번은 걸었을 테니 1로 적어둡니다.
    call_count = meta_info.get("call_count", 1)
    # [1차]: meta_info에서 "elapsed"(소요 시간)를 추출하고, 없으면 기본값 0.0을 사용합니다.
    # [2차]: 스톱워치에 찍힌 시간(초)을 가져오되, 측정을 깜빡했으면 0.0초로 표시합니다.
    elapsed = meta_info.get("elapsed", 0.0)
    # [1차]: meta_info에서 사용된 AI 모델명을 추출하고, 없으면 "gpt-4o-mini"를 기본값으로 취합니다.
    # [2차]: 어떤 AI 일꾼(gpt-4o-mini 등)에게 일을 시켰는지 이름을 확인합니다.
    model = meta_info.get("model", "gpt-4o-mini")
    # [1차]: meta_info에서 temperature(생성 다양성) 값을 추출하고, 없으면 0.2를 기본값으로 사용합니다.
    # [2차]: AI 일꾼이 얼마나 얌전하게 작성했는지(온도 0.2 = 아주 차분하고 정확함) 수치를 읽어옵니다.
    temperature = meta_info.get("temperature", 0.2)
    # [1차]: meta_info에서 max_tokens 설정을 추출하고, 없으면 300을 기본값으로 사용합니다.
    # [2차]: AI가 적을 수 있는 최대 글자 수 한도(토큰 300개)가 얼마였는지 꺼내옵니다.
    max_tokens = meta_info.get("max_tokens", 300)
    # [1차]: meta_info에서 safe_mode 불리언 값을 추출하고, 없으면 True(안전 모드 활성화)를 적용합니다.
    # [2차]: 비밀번호 먹칠 보안 검사를 켰는지(True) 껐는지(False) 확인합니다.
    safe_mode = meta_info.get("safe_mode", True)
    repo = meta_info.get("repo")

    # [1차]: 터미널에 세로로 한 줄씩 출력할 문자열 요소들을 순서대로 담아둘 lines 리스트를 생성합니다.
    # [2차]: 화면에 찍어낼 문장들을 차곡차곡 쌓을 출력 바구니를 하나 준비합니다.
    lines = [
        # [1차]: 출력 박스의 최상단 굵은 이중 구분선("===")을 리스트에 추가합니다.
        # [2차]: 액자의 제일 위쪽 뚜껑 테두리를 덮습니다.
        DIVIDER_DOUBLE,
        # [1차]: 전달받은 title을 포함하는 결과 제목 헤더 라인을 f-string으로 포맷팅하여 추가합니다.
        # [2차]: "★ 결과 발표: 커밋 메시지 초안 ★"이라는 문패를 상단 테두리 바로 아래에 붙입니다.
        f"  [생성 결과: {title}]",
        # [1차]: 제목 헤더와 본문 사이를 가르는 얇은 단일 구분선("---")을 추가합니다.
        # [2차]: 제목과 본문 내용이 서로 엉겨붙지 않도록 중간 칸막이를 놓습니다.
        DIVIDER_SINGLE,
        # [1차]: content 문자열 앞뒤의 불필요한 공백과 줄바꿈을 제거(strip)한 본문 내용을 추가합니다.
        # [2차]: 내용물 앞뒤에 붙은 너저분한 먼지나 여백을 가위로 싹둑 다듬어서 정중앙에 배치합니다.
        content.strip(),
        # [1차]: 본문 내용과 하단 메타정보 섹션을 분리하는 얇은 구분선("---")을 추가합니다.
        # [2차]: 편지 본문이 끝났으니, 이제 날짜와 발신자 정보를 적을 바닥 칸막이를 칩니다.
        DIVIDER_SINGLE,
        # [1차]: 실행 메타정보 섹션의 시작을 알리는 레이블 텍스트를 추가합니다.
        # [2차]: "--- [작업 영수증 정보] ---" 소제목을 찍습니다.
        "  [실행 메타정보]",
        # [1차]: AI API 호출 횟수를 f-string으로 포맷팅하여 추가합니다.
        # [2차]: "API 호출 횟수: 1회 (돈 낭비 없이 1번에 끝냈음!)"을 보여줍니다.
        f"  * AI API 호출 횟수 : {call_count}회",
        # [1차]: API 소요 시간을 소수점 둘째 자리까지 표기(:.2f)하여 추가합니다.
        # [2차]: "걸린 시간: 1.23초"처럼 소수점 둘째 자리까지 딱 떨어지게 스톱워치 기록을 찍습니다.
        f"  * 소요 시간        : {elapsed:.2f}초",
        # [1차]: 사용 모델명과 주요 생성 파라미터(temperature, max_tokens) 요약 라인을 추가합니다.
        # [2차]: "어떤 기계(gpt-4o-mini)로 어떤 세팅값으로 뽑았는지"를 투명하게 공개하는 스펙 라벨입니다.
        f"  * 사용 모델        : {model} (temp={temperature}, max_tokens={max_tokens})",
        # [1차]: safe_mode 값에 따라 '적용됨 (ON)' 또는 '미적용 (OFF)'을 동적으로 선택해 표시합니다.
        # [2차]: "보안 먹칠 필터: 켜짐" 스티커를 붙여서 개발자가 안심할 수 있게 해줍니다.
        f"  * 보안 안전 모드   : {'적용됨 (ON)' if safe_mode else '미적용 (OFF)'}",
    ]

    # [1차]: repo 경로 정보가 제공되었을 경우 메타정보 섹션에 추가합니다.
    # [2차]: 사용자가 어느 폴더(저장소)를 대상으로 커밋을 만들었는지 영수증에 주소를 적어줍니다.
    if repo:
        lines.append(f"  * 대상 저장소      : {repo}")

    lines.extend([
        # [1차]: 메타정보 섹션을 닫는 굵은 이중 구분선("===")을 추가합니다.
        # [2차]: 영수증의 데이터 출력이 끝났음을 알리는 굵은 가로선입니다.
        DIVIDER_DOUBLE,
        # [1차]: AI 생성 초안이므로 개발자의 최종 검토가 필수임을 알리는 안내 경고문을 추가합니다.
        # [2차]: "※ 경고: AI가 썼으니 git push 하기 전에 네가 직접 한 번 더 읽어봐라!"라는 안전벨트 안내문입니다.
        "  [안내] 위 결과물은 AI가 생성한 초안입니다. 반드시 검토 후 적용하세요.",
        # [1차]: 포맷 박스의 최하단을 완벽하게 마감하는 굵은 이중 구분선("===")을 추가합니다.
        # [2차]: 액자의 제일 아래쪽 밑바닥 받침대를 조립하여 상자를 완전히 완성합니다.
        DIVIDER_DOUBLE,
    # [1차]: lines 리스트 정의를 닫습니다.
    # [2차]: 출력 바구니 담기 완료.
    ])

    # [1차]: lines 리스트의 각 줄을 줄바꿈 문자("\n")로 결합하여 하나의 통합된 문자열을 반환합니다.
    # [2차]: 바구니에 담긴 문장들을 세로로 길게 풀칠해서 하나의 완벽한 포스터로 만들어 손님에게 건넵니다.
    return "\n".join(lines)
